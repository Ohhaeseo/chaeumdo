import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const base = process.env.API_URL || "http://127.0.0.1:8080/api";
const id = `test_${crypto.randomUUID().replaceAll("-", "").slice(0, 12)}`;
const password = "Test-password-2026";
const json = (body) => ({ method: "POST", headers: { "X-Requested-With": "chaeummdo", "Content-Type": "application/json" }, body: JSON.stringify(body) });
const register = await fetch(base + "/auth/register", json({ username: id, displayName: "검증", password }));
if (register.status !== 200) throw new Error(`Registration failed: ${register.status} ${await register.text()}`);
const recoveryCode = (await register.json()).recoveryCode;
const accountCookie = register.headers.get("set-cookie").split(";")[0];
assert.equal((await fetch(base + "/auth/register", json({ username: id.toUpperCase(), displayName: "중복", password }))).status, 409);
const me = await fetch(base + "/auth/me", { headers: { Cookie: accountCookie } });
assert.equal(me.status, 200);
assert.equal((await me.json()).username, id);
const wrong = await fetch(base + "/auth/login", json({ username: id, password: "incorrect" }));
assert.equal(wrong.status, 401);
const status = async (cookie) => (await fetch(base + "/auth/me", { headers: { Cookie: cookie } })).status;
const signIn = async (pass, cookie) => {
  const response = await fetch(base + "/auth/login", { ...json({ username: id, password: pass }), headers: { ...json({}).headers, ...(cookie ? { Cookie: cookie } : {}) } });
  assert.equal(response.status, 200);
  return response.headers.get("set-cookie").split(";")[0];
};
const signOut = async (cookie) => assert.equal((await fetch(base + "/auth/logout", { method: "POST", headers: { Cookie: cookie, "X-Requested-With": "chaeummdo" } })).status, 200);
// Each device keeps its own session: signing in elsewhere must not sign out the device that registered.
const loggedCookie = await signIn(password);
assert.notEqual(loggedCookie, accountCookie);
assert.equal(await status(accountCookie), 200, "registration session survives a login on another device");
assert.equal(await status(loggedCookie), 200);
const tabletCookie = await signIn(password);
assert.equal(await status(tabletCookie), 200);
await signOut(tabletCookie);
assert.equal(await status(tabletCookie), 401, "logout ends the current session");
assert.equal(await status(accountCookie), 200, "logout leaves other devices signed in");
assert.equal(await status(loggedCookie), 200, "logout leaves other devices signed in");
// Signing in again from the same browser replaces that browser's session instead of piling up sessions.
const renewedCookie = await signIn(password, accountCookie);
assert.equal(await status(accountCookie), 401, "the replaced session of the same browser ends");
assert.equal(await status(renewedCookie), 200);
const picture = await readFile(new URL("../frontend/public/fonts/에스코어 드림_라이선스.png", import.meta.url));
const form = new FormData();
form.append("file", new Blob([picture], { type: "image/png" }), "test.png");
const photo = await fetch(base + "/photos", { method: "POST", headers: { Cookie: loggedCookie, "X-Requested-With": "chaeummdo" }, body: form });
assert.equal(photo.status, 200);
const { id: photoId } = await photo.json();
const trip = await fetch(base + "/trips", { ...json({ requestId: crypto.randomUUID(), regionId: "26", photoId, startDate: "2026-10-01", endDate: "2026-10-01", companion: "민지,준호", days: [["해변"]], placePhotoIds: [[photoId]] }), headers: { ...json({}).headers, Cookie: loggedCookie } });
assert.equal(trip.status, 200);
const saved = await (await fetch(base + "/trips", { headers: { Cookie: loggedCookie } })).json();
assert.equal(saved.length, 1);
assert.equal(saved[0].companion, "민지,준호");
assert.equal(saved[0].placePhotoUrls[0][0], `/api/photos/${photoId}`);
assert.equal((await (await fetch(base + "/trips", { headers: { Cookie: renewedCookie } })).json()).length, 1, "another device of the account sees the same records");
const recovered = await fetch(base + "/auth/recover-id", json({ recoveryCode }));
assert.equal((await recovered.json()).username, id);
const reset = await fetch(base + "/auth/reset-password", json({ username: id, recoveryCode, newPassword: "Updated-password-2026" }));
assert.equal(reset.status, 200);
const nextCode = (await reset.json()).recoveryCode;
assert.notEqual(nextCode, recoveryCode);
const nextCookie = reset.headers.get("set-cookie").split(";")[0];
for (const cookie of [renewedCookie, loggedCookie]) assert.equal(await status(cookie), 401, "password reset signs out every existing session");
assert.equal((await fetch(base + "/trips", { headers: { Cookie: loggedCookie } })).status, 401, "a revoked session cannot read records");
assert.equal(await status(nextCookie), 200, "the device that reset the password gets a new session");
const phoneCookie = await signIn("Updated-password-2026");
assert.equal(await status(phoneCookie), 200);
for (let attempt = 1; attempt <= 4; attempt++) assert.equal((await fetch(base + "/auth/login", json({ username: id, password: "incorrect" }))).status, 401);
assert.equal((await fetch(base + "/auth/login", json({ username: id, password: "incorrect" }))).status, 401, "fifth failure locks the account");
assert.equal((await fetch(base + "/auth/login", json({ username: id, password: "Updated-password-2026" }))).status, 429, "locked account rejects even the right password");
const del = await fetch(base + "/auth/delete", { ...json({ password: "Updated-password-2026" }), headers: { ...json({}).headers, Cookie: nextCookie } });
assert.equal(del.status, 200);
for (const cookie of [nextCookie, phoneCookie]) assert.equal(await status(cookie), 401, "account deletion signs out every device");
assert.equal((await fetch(base + "/photos/" + photoId, { headers: { Cookie: phoneCookie } })).status, 401, "a deleted account's session cannot read photos");
